"""Load the simulation settings from launch_config.yaml and build common launch actions.

The YAML file is generated by ``scripts/generate_launch_config.py`` and installed
into the package share directory when the package is built. It looks like::

    sim_environment:
      sim_repo_path: "/home/user/pose_estimator_sim"
      px4_repo_path: "/home/user/PX4-Autopilot"
      world: "cats_world"            # one of: cats_world, tugbot_depot
"""

import filecmp
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List

# Supported Gazebo worlds.
# Key: value stored in launch_config.yaml.
# Value: folder (inside the simulation repo) and SDF file to load.
WORLDS: Dict[str, Dict[str, str]] = {
    "cats_world": {
        "folder": "cats_world",
        "sdf": "cats_world.sdf",
        "description": "Indoor room with obstacles, window tunnels and a landing platform",
    },
    "tugbot_depot": {
        "folder": "tugbot_depot",
        "sdf": "tugbot_depot.sdf",
        "description": "Warehouse (Depot model is downloaded from Gazebo Fuel, needs internet)",
    },
}

DEFAULT_WORLD = "cats_world"

# Location of the x500 drone model that PX4 spawns, relative to the PX4 repo.
PX4_X500_MODEL = Path("Tools/simulation/gz/models/x500/model.sdf")

# Maximum time (seconds) to wait for the Gazebo world before starting PX4.
GZ_WORLD_TIMEOUT_S = 120


@dataclass(frozen=True)
class SimConfig:
    """Resolved simulation settings."""

    sim_repo: Path
    px4_repo: Path
    world: str
    world_dir: Path
    world_file: Path


def get_config_path() -> Path:
    """Return the path of the launch_config.yaml installed with the package."""
    # Imported here so this module can also be used without a sourced ROS 2 setup
    # (e.g. by scripts/generate_launch_config.py, which only needs WORLDS).
    from ament_index_python.packages import get_package_share_directory

    return Path(get_package_share_directory("pose_estimator_pkg")) / "launch_config.yaml"


def load_sim_config() -> SimConfig:
    """Read, validate and resolve the simulation settings from launch_config.yaml."""
    import yaml

    config_path = get_config_path()
    regenerate_hint = (
        "Run 'python3 scripts/generate_launch_config.py' inside pose_estimator_pkg "
        "and rebuild the package with colcon."
    )

    try:
        with config_path.open(encoding="utf-8") as config_file:
            config = yaml.safe_load(config_file) or {}
    except OSError as exc:
        raise RuntimeError(f"Could not read {config_path}. {regenerate_hint}") from exc
    except yaml.YAMLError as exc:
        raise RuntimeError(f"Invalid YAML in {config_path}: {exc}") from exc

    if not isinstance(config, dict) or not isinstance(config.get("sim_environment"), dict):
        raise RuntimeError(
            f"Missing 'sim_environment' section in {config_path}. {regenerate_hint}"
        )
    environment = config["sim_environment"]

    sim_repo = _required_dir(environment, "sim_repo_path", config_path, regenerate_hint)
    px4_repo = _required_dir(environment, "px4_repo_path", config_path, regenerate_hint)

    world = environment.get("world")
    if world not in WORLDS:
        raise RuntimeError(
            f"Invalid 'world' value in {config_path}: {world!r}. "
            f"Valid options: {', '.join(WORLDS)}. {regenerate_hint}"
        )

    world_dir = sim_repo / WORLDS[world]["folder"]
    world_file = world_dir / WORLDS[world]["sdf"]
    if not world_file.is_file():
        raise RuntimeError(f"The world file for '{world}' does not exist: {world_file}")

    return SimConfig(sim_repo, px4_repo, world, world_dir, world_file)


def build_simulation_actions(config: SimConfig) -> List:
    """Return the actions shared by every launch file.

    1. Micro XRCE-DDS Agent (PX4 <-> ROS 2 communication).
    2. Gazebo with the selected world.
    3. PX4 SITL, which attaches to the running Gazebo world and spawns the x500.
    """
    from launch.actions import ExecuteProcess, LogInfo

    actions = [LogInfo(msg=f"[pose_estimator_pkg] Gazebo world: {config.world} "
                           f"({config.world_file})")]
    warning = _check_px4_drone_model(config)
    if warning:
        actions.append(LogInfo(msg=warning))

    # Gazebo runs from inside the world folder and that folder is added to the
    # resource path, so 'model://...' URIs (textures, meshes) are resolved.
    resource_path = os.pathsep.join(
        p for p in (os.environ.get("GZ_SIM_RESOURCE_PATH", ""), str(config.world_dir)) if p
    )

    microxrce_agent = ExecuteProcess(
        cmd=["MicroXRCEAgent", "udp4", "--port", "8888"],
        output="screen",
    )

    gz_sim = ExecuteProcess(
        cmd=["gz", "sim", "-r", str(config.world_file)],
        cwd=str(config.world_dir),
        additional_env={"GZ_SIM_RESOURCE_PATH": resource_path},
        output="screen",
    )

    # PX4 looks for a running Gazebo world when it starts. If none is found it
    # opens its own empty 'default' world, so wait until our world publishes its
    # clock topic before starting PX4 (tugbot_depot can take a while because the
    # Depot model is downloaded from Gazebo Fuel).
    wait_for_world = (
        f"echo '[pose_estimator_pkg] Waiting for Gazebo world {config.world}...'; "
        f"for i in $(seq 1 {GZ_WORLD_TIMEOUT_S}); do "
        "gz topic -l 2>/dev/null | grep -q -e '^/world/.*/clock$' && break; "
        "sleep 1; done; "
        "if ! gz topic -l 2>/dev/null | grep -q -e '^/world/.*/clock$'; then "
        f"echo '[pose_estimator_pkg] ERROR: Gazebo world not ready after "
        f"{GZ_WORLD_TIMEOUT_S} s, PX4 not started.'; exit 1; fi; "
    )
    px4_sitl = ExecuteProcess(
        cmd=["/bin/bash", "-lc", wait_for_world + "HEADLESS=1 make px4_sitl gz_x500"],
        cwd=str(config.px4_repo),
        output="screen",
    )

    return actions + [microxrce_agent, gz_sim, px4_sitl]


def _check_px4_drone_model(config: SimConfig) -> str:
    """Warn if the x500 model installed in PX4 is not the one for the selected world.

    Each world folder has its own x500/model.sdf (same sensors, different spawn
    pose), and PX4 always spawns the model stored in its own models folder.
    """
    expected = config.world_dir / "x500" / "model.sdf"
    installed = config.px4_repo / PX4_X500_MODEL
    if not expected.is_file() or not installed.is_file():
        return ""
    if filecmp.cmp(expected, installed, shallow=False):
        return ""
    return (
        f"[pose_estimator_pkg] WARNING: the x500 model in PX4 does not match the "
        f"'{config.world}' world. The drone may spawn in the wrong place or without "
        f"cameras. To fix it run:\n    cp {expected} {installed}"
    )


def _required_dir(environment: dict, key: str, config_path: Path, hint: str) -> Path:
    """Read a non-empty directory path from the YAML and make sure it exists."""
    value = environment.get(key)
    if not isinstance(value, str) or not value.strip():
        raise RuntimeError(f"Missing '{key}' in {config_path}. {hint}")
    path = Path(value).expanduser().resolve()
    if not path.is_dir():
        raise RuntimeError(f"The directory set in '{key}' does not exist: {path}")
    return path
